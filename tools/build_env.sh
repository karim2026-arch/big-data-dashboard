#!/usr/bin/env bash
# Builds the project .env from the local secret files. Prints no secrets.
#   AWS keys       : ~/.aws/credentials  ([default] profile)
#   Snowflake keys : ~/.snowflake_keys/{airbyte,dbt}_rsa_key.p8
# Re-run after any key changes (for example a new AWS key from the owner).
# Usage (Git Bash, project root): bash tools/build_env.sh
set -euo pipefail

ENV_FILE=".env"
AWS_CREDS="$HOME/.aws/credentials"
SF_KEYS="$HOME/.snowflake_keys"

aws_value() {  # value of a key in the [default] profile, trimmed
  awk -F'=' -v k="$1" '
    /^\[/ { in_default = ($0 == "[default]") }
    in_default && $1 ~ "^[ \t]*" k "[ \t]*$" { sub(/^[^=]*=[ \t]*/, ""); sub(/[ \t\r]+$/, ""); print; exit }
  ' "$AWS_CREDS"
}

for f in "$AWS_CREDS" "$SF_KEYS/airbyte_rsa_key.p8" "$SF_KEYS/dbt_rsa_key.p8"; do
  [ -f "$f" ] || { echo "Missing: $f" >&2; exit 1; }
done

cat > "$ENV_FILE" <<EOF
# Generated by tools/build_env.sh - do not commit (git-ignored)

# AWS (S3 bronze bucket)
AWS_ACCESS_KEY_ID=$(aws_value aws_access_key_id)
AWS_SECRET_ACCESS_KEY=$(aws_value aws_secret_access_key)
AWS_DEFAULT_REGION=eu-north-1
S3_BUCKET=fleet-telematics-lakehouse-team11

# Snowflake account
SNOWFLAKE_ACCOUNT=RSGNWLJ-PK32132
SNOWFLAKE_DATABASE=FLEET_DB

# Snowflake: Airbyte service user (writes RAW)
SNOWFLAKE_AIRBYTE_USER=AIRBYTE_USER
SNOWFLAKE_AIRBYTE_ROLE=AIRBYTE_ROLE
SNOWFLAKE_AIRBYTE_WAREHOUSE=AIRBYTE_WH
SNOWFLAKE_AIRBYTE_SCHEMA=RAW
SNOWFLAKE_AIRBYTE_PRIVATE_KEY="$(tr -d '\r' < "$SF_KEYS/airbyte_rsa_key.p8")"

# Snowflake: dbt service user (builds STAGING / INTERMEDIATE / MARTS)
SNOWFLAKE_DBT_USER=DBT_USER
SNOWFLAKE_DBT_ROLE=TRANSFORMER
SNOWFLAKE_DBT_WAREHOUSE=DBT_WH
SNOWFLAKE_DBT_SCHEMA=STAGING
SNOWFLAKE_DBT_PRIVATE_KEY="$(tr -d '\r' < "$SF_KEYS/dbt_rsa_key.p8")"
EOF

echo "Wrote $ENV_FILE ($(grep -c '=' "$ENV_FILE") settings). Secrets not printed."
git check-ignore -q "$ENV_FILE" && echo "OK: $ENV_FILE is git-ignored" || echo "WARNING: $ENV_FILE is NOT git-ignored" >&2
