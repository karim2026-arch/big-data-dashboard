"""Reads the map data once from DBT_MARTS and writes it to dashboard/src/data/facilities.js (hardcoded, no backend call):
- FACILITIES: the facilities of DIM_FACILITY with their city / state_code from DIM_LOCATION.
- MAP_BOUNDS: min/max latitude and longitude of all DIM_LOCATION and DIM_FACILITY points = the area the 3D map shows.
Run it again only when facilities or locations change in the warehouse.
Uses the backend's Snowflake login (backend/.env, schema DBT_MARTS).
Run from the project root: .venv/Scripts/python tools/export_map_data.py"""
import json
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from app.infrastructure import snowflake_client  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[1] / "dashboard" / "src" / "data" / "facilities.js"

FACILITIES_SQL = """
SELECT f.facility_id, f.facility_name, f.facility_type, l.city, l.state_code, f.latitude, f.longitude
FROM dim_facility f
JOIN dim_location l ON l.location_key = f.location_key
ORDER BY f.facility_id
"""
BOUNDS_SQL = """
SELECT MIN(latitude) AS min_lat, MAX(latitude) AS max_lat, MIN(longitude) AS min_lon, MAX(longitude) AS max_lon
FROM (SELECT latitude, longitude FROM dim_location UNION ALL SELECT latitude, longitude FROM dim_facility)
"""


def rows(sql: str) -> list[dict]:
    """Rows with lowercase keys (the dashboard's data names) and decimals as floats."""
    return [{key.lower(): float(value) if isinstance(value, Decimal) else value for key, value in row.items()}
            for row in snowflake_client.fetch_all(sql)]


def main() -> None:
    facilities = rows(FACILITIES_SQL)
    bounds = rows(BOUNDS_SQL)[0]
    snowflake_client.close_connection()
    lines = ",\n".join(f"  {json.dumps(facility)}" for facility in facilities)
    OUTPUT.write_text(
        f"// Generated by tools/export_map_data.py from DBT_MARTS on {date.today()}. Do not edit by hand: run the script again.\n"
        "// Facilities (DIM_FACILITY + DIM_LOCATION city/state_code) and the area of all DIM_LOCATION + DIM_FACILITY points (degrees).\n"
        f"export const MAP_BOUNDS = {json.dumps(bounds)}\n\n"
        f"export const FACILITIES = [\n{lines},\n]\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(facilities)} facilities and bounds {bounds} to {OUTPUT}")


if __name__ == "__main__":
    main()
